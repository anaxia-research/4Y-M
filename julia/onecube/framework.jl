# Recording of checks and export of the rational enclosures to Lean.

const RESULTS = Vector{NamedTuple}()
const LEANLINES = String[]
const COUNTER = Dict{String,Int}()

leanrat(q::Rational) = denominator(q) == 1 ? "($(numerator(q)) : ℚ)" :
                                             "(($(numerator(q))) / $(denominator(q)) : ℚ)"
const OPSTR = Dict(:lt => "<", :le => "≤", :gt => ">", :ge => "≥")

function nextname(id)
    COUNTER[id] = get(COUNTER, id, 0) + 1
    "$(id)_$(COUNTER[id])"
end

holds(x::Rational, op, b::Rational) =
    op == :lt ? x < b : op == :le ? x <= b : op == :gt ? x > b : x >= b

function report(id, label, pass, detail)
    push!(RESULTS, (id = id, label = label, pass = pass))
    println(rpad(id, 5), pass ? "PASS  " : "FAIL  ", label, "   ", detail)
end

"""Interval claim `x op bound` (op ∈ :lt, :le, :gt, :ge). The decisive endpoint
of the enclosure is rounded outward to a short decimal rational `r`, and the
rational inequality `r op bound` is exported to Lean."""
function claim(id, label, x::Iv, op::Symbol, bound::Rational)
    upper = op in (:lt, :le)
    endpt = upper ? x.hi : x.lo
    pass = holds(Rational(endpt), op, bound)
    r = nothing
    if pass
        for nd in 3:70
            c = upper ? short_up(endpt, nd) : short_dn(endpt, nd)
            if holds(c, op, bound)
                r = c; break
            end
        end
    end
    detail = "enclosure $(x)" * (r === nothing ? "" : "  exported $(upper ? "≤" : "≥") $(Float64(r)) = $(r)")
    report(id, label, pass, detail)
    if r !== nothing
        name = nextname(id)
        push!(LEANLINES, "/-- $id: $label. Julia enclosure: quantity $(upper ? "≤" : "≥") the left side. -/")
        push!(LEANLINES, "theorem $name : $(leanrat(r)) $(OPSTR[op]) $(leanrat(bound)) := by norm_num")
        push!(LEANLINES, "")
    end
    pass
end

"""Exact rational claim `x op bound`, also exported to Lean."""
function claimq(id, label, x::Rational, op::Symbol, bound::Rational)
    pass = holds(x, op, bound)
    report(id, label, pass, "exact value $(Float64(x)) $(OPSTR[op]) $(Float64(bound))")
    if pass
        name = nextname(id)
        push!(LEANLINES, "/-- $id: $label (exact). -/")
        push!(LEANLINES, "theorem $name : $(leanrat(x)) $(OPSTR[op]) $(leanrat(bound)) := by norm_num")
        push!(LEANLINES, "")
    end
    pass
end

"""A check whose result is only reported (exact computation done in Julia)."""
check(id, label, pass::Bool, detail = "") = (report(id, label, pass, detail); pass)

function write_lean(path)
    open(path, "w") do io
        println(io, "import Mathlib")
        println(io)
        println(io, "/-!")
        println(io, "# One-cube criteria: rational re-check of the Julia enclosures (J1–J14)")
        println(io)
        println(io, "Generated by `julia/onecube/run_all.jl`; do not edit by hand.")
        println(io, "Each theorem is the rational inequality obtained after Julia replaced a")
        println(io, "transcendental quantity by an outward-rounded endpoint of its enclosure")
        println(io, "(BigFloat, MPFR directed rounding). The inequalities between the")
        println(io, "transcendental quantities themselves are proved directly, where feasible,")
        println(io, "in `YangMills.OneCube.Transcendental`.")
        println(io, "-/")
        println(io)
        println(io, "namespace YangMills.OneCube.Enclosures")
        println(io)
        foreach(l -> println(io, l), LEANLINES)
        println(io, "end YangMills.OneCube.Enclosures")
    end
end
